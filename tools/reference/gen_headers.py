#!/usr/bin/env python3
"""Generate C headers from config/platform.json and the NumPy reference:

  mcue/include/mcue/platform_config.h   geometry, payload and limits (#defines)
  tests/unit/src/kin_vectors.h          IK, statics and workspace vectors from mcue_ref.py

Usage: gen_headers.py           # write both
       gen_headers.py --check   # fail if either is stale (CI)
"""
from __future__ import annotations

import argparse
import json
import math
import re
import sys

import numpy as np

from mcue_ref import CONFIG, ROOT, ik, load_geometry, statics, valid, ws_limit

CONFIG_H = ROOT / "mcue" / "include" / "mcue" / "platform_config.h"
VECTORS_H = ROOT / "tests" / "unit" / "src" / "kin_vectors.h"
D = math.radians


def render_config(cfg: dict) -> str:
    g, p, lim = cfg["geometry"], cfg["payload"], cfg["limits"]
    rows = [
        ("MC_CFG_BASE_RADIUS_M", g["base_radius_m"]),
        ("MC_CFG_PLATFORM_RADIUS_M", g["platform_radius_m"]),
        ("MC_CFG_BASE_HALF_ANGLE_DEG", g["base_half_angle_deg"]),
        ("MC_CFG_PLATFORM_HALF_ANGLE_DEG", g["platform_half_angle_deg"]),
        ("MC_CFG_NEUTRAL_HEIGHT_M", g["neutral_height_m"]),
        ("MC_CFG_STROKE_M", g["stroke_m"]),
        ("MC_CFG_SOFT_MARGIN_M", g["soft_margin_m"]),
        ("MC_CFG_PAYLOAD_KG", p["mass_kg"]),
        ("MC_CFG_PAYLOAD_COM_X_M", p["com_platform_m"][0]),
        ("MC_CFG_PAYLOAD_COM_Y_M", p["com_platform_m"][1]),
        ("MC_CFG_PAYLOAD_COM_Z_M", p["com_platform_m"][2]),
        ("MC_CFG_LEG_SPEED_M_S", lim["leg_speed_m_s"]),
        ("MC_CFG_LEG_ACCEL_M_S2", lim["leg_accel_m_s2"]),
    ]
    w = cfg["washout"]
    rows += [(f"MC_CFG_WO_{k.upper()}", v) for k, v in w.items()]
    for section, prefix in (("actuator", "ACT"), ("servo", "SRV"), ("safety", "SAF")):
        rows += [(f"MC_CFG_{prefix}_{k.upper()}", v) for k, v in cfg[section].items()]
    out = ["/* GENERATED by tools/reference/gen_headers.py from config/platform.json. Do not edit. */",
           "#ifndef MCUE_PLATFORM_CONFIG_H_", "#define MCUE_PLATFORM_CONFIG_H_", ""]
    out += [f"#define {name:32s} {float(v)!r}" for name, v in rows]
    out += ["", "#endif /* MCUE_PLATFORM_CONFIG_H_ */", ""]
    return "\n".join(out)


def poses(g):
    named = [
        ("neutral", (0, 0, 0, 0, 0, 0)),
        ("heave +50 mm", (0, 0, 0.05, 0, 0, 0)),
        ("surge +100 mm", (0.10, 0, 0, 0, 0, 0)),
        ("sway -80 mm", (0, -0.08, 0, 0, 0, 0)),
        ("roll 10 deg", (0, 0, 0, D(10), 0, 0)),
        ("pitch -12 deg", (0, 0, 0, 0, D(-12), 0)),
        ("yaw 20 deg", (0, 0, 0, 0, 0, D(20))),
        ("combined", (0.05, -0.04, 0.03, D(4), D(-6), D(8))),
    ]
    rng = np.random.default_rng(2026)
    lim = np.array([0.15, 0.15, 0.10, D(10), D(10), D(20)])
    k = 0
    while k < 12:
        q = rng.uniform(-lim, lim)
        if valid(g, q):
            named.append((f"random {k}", tuple(q)))
            k += 1
    return named


def excessive(g):
    """Commands outside the workspace and the scale the reference bisection finds."""
    cmds = [("surge 0.5 m", (0.5, 0, 0, 0, 0, 0)),
            ("pitch 30 deg + heave", (0, 0, 0.08, 0, D(30), 0)),
            ("everything", (0.3, 0.3, 0.2, D(20), D(20), D(40))),
            ("yaw 60 deg", (0, 0, 0, 0, 0, D(60)))]
    return [(n, q, ws_limit(g, q)[1]) for n, q in cmds]


def fmt(v):
    return ", ".join(f"{x:.17g}" for x in v)


def render_vectors() -> str:
    g = load_geometry()
    cfg = json.loads(CONFIG.read_text())["payload"]
    out = ["/* GENERATED by tools/reference/gen_headers.py (NumPy reference). Do not edit. */",
           "#ifndef KIN_VECTORS_H_", "#define KIN_VECTORS_H_", "",
           "struct kin_vector {", "\tconst char *name;", "\tdouble pose[6]; /* x y z roll pitch yaw */",
           "\tdouble legs[6];", "\tdouble force[6]; /* statics, payload from platform.json */", "};", "",
           f"#define KIN_VEC_L0 {g.l0:.17g}", "",
           "static const struct kin_vector kin_vectors[] = {"]
    for name, q in poses(g):
        legs = ik(g, q)
        f = statics(g, q, cfg["mass_kg"], cfg["com_platform_m"])
        out.append(f'\t{{"{name}", {{{fmt(q)}}}, {{{fmt(legs)}}}, {{{fmt(f)}}}}},')
    out += ["};", "", "struct ws_vector {", "\tconst char *name;", "\tdouble cmd[6];",
            "\tdouble scale; /* from the reference bisection */", "};", "",
            "static const struct ws_vector ws_vectors[] = {"]
    for name, q, s in excessive(g):
        out.append(f'\t{{"{name}", {{{fmt(q)}}}, {s:.17g}}},')
    out += ["};", "", "#endif /* KIN_VECTORS_H_ */", ""]
    return "\n".join(out)


NUMBER = re.compile(r"-?\d+(?:\.\d*)?(?:[eE][-+]?\d+)?")


def same(old: str, new: str) -> bool:
    """Equal text, numbers equal to 1e-9 relative. The statics forces come from
    a LAPACK solve whose last bits depend on the CPU the BLAS kernel picks, so
    a byte compare fails on some CI runners; a real change moves them far more."""
    if NUMBER.sub("#", old) != NUMBER.sub("#", new):
        return False
    return all(math.isclose(float(a), float(b), rel_tol=1e-9, abs_tol=1e-9)
               for a, b in zip(NUMBER.findall(old), NUMBER.findall(new)))


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    files = {CONFIG_H: render_config(json.loads(CONFIG.read_text())), VECTORS_H: render_vectors()}
    stale = [p for p, text in files.items() if not p.exists() or not same(p.read_text(), text)]
    if a.check:
        for p in stale:
            print(f"{p.relative_to(ROOT)} is out of date: run tools/reference/gen_headers.py",
                  file=sys.stderr)
        if not stale:
            print("generated headers are up to date")
        return 1 if stale else 0
    for p, text in files.items():
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(text)
        print(f"wrote {p.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
